-- 1. 기존 테이블 삭제 (순서 중요: 자식 → 부모)
DROP TABLE excluded_keyword CASCADE CONSTRAINTS;
DROP TABLE used_keyword CASCADE CONSTRAINTS;
DROP TABLE product CASCADE CONSTRAINTS;

-- 2.1. product 테이블 (부모 테이블)
CREATE TABLE product (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword VARCHAR2(255),
    product_name VARCHAR2(500) NOT NULL,
    product_name_cn VARCHAR2(500),
    price VARCHAR2(50),
    description CLOB,
    rating VARCHAR2(20),
    product_url VARCHAR2(2048),
    image_url VARCHAR2(2048),
    local_image_path VARCHAR2(1024),
    crawl_type VARCHAR2(20),
    ocr_text CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- product 테이블 유니크 인덱스 및 인덱스
CREATE UNIQUE INDEX uq_product_url ON product (SUBSTR(product_url, 1, 255));
CREATE INDEX idx_product_keyword ON product (keyword);
CREATE INDEX idx_product_created_at ON product (created_at);

-- 2.2. used_keyword 테이블 (product를 참조하는 자식 테이블)
CREATE TABLE used_keyword (
    keyword_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER,
    keyword VARCHAR2(255) NOT NULL,
    source VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- used_keyword 테이블 인덱스
CREATE INDEX idx_used_keyword_keyword ON used_keyword (keyword);
CREATE INDEX idx_used_keyword_used_date ON used_keyword (created_at);

-- used_keyword 외래 키 제약조건
ALTER TABLE used_keyword 
ADD CONSTRAINT fk_used_keyword_product 
FOREIGN KEY (product_id) REFERENCES product(product_id) 
ON DELETE CASCADE;

-- 2.3. excluded_keyword 테이블 (used_keyword를 참조하는 자식 테이블)
CREATE TABLE excluded_keyword (
    excluded_keyword_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id NUMBER,
    excluded_keyword VARCHAR2(255) NOT NULL,
    source VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- excluded_keyword 테이블 유니크 인덱스 및 인덱스
CREATE UNIQUE INDEX uq_excluded_keyword ON excluded_keyword (excluded_keyword);
CREATE INDEX idx_excluded_created_at ON excluded_keyword (created_at);

-- excluded_keyword 외래 키 제약조건
ALTER TABLE excluded_keyword 
ADD CONSTRAINT fk_excluded_keyword_used 
FOREIGN KEY (keyword_id) REFERENCES used_keyword(keyword_id) 
ON DELETE CASCADE;

-- 3. 확인용 테이블 구조 출력
SELECT table_name FROM user_tables WHERE table_name IN ('PRODUCT', 'USED_KEYWORD', 'EXCLUDED_KEYWORD');

